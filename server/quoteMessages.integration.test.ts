import {beforeAll,describe,expect,it} from 'vitest';
import {randomUUID} from 'node:crypto';
import {eq} from 'drizzle-orm';
import {getDb,createQuoteRequest,createQuoteMessage,getQuoteMessages} from './db';
import {users,messages,quoteRequests,quoteMessageRequests} from '../drizzle/schema';
const url=process.env.RAERO_TEST_DATABASE_URL;
describe.skipIf(!url)('quote message access · PostgreSQL',()=>{
 beforeAll(()=>{process.env.DATABASE_URL=url!;});
 it('validates direct input, restricts read/write to active participants and marks only incoming messages read',async()=>{
  const db=(await getDb())!;
  const [owner]=await db.insert(users).values({openId:randomUUID(),email:randomUUID()+'@example.com'}).returning();
  const [admin]=await db.insert(users).values({openId:randomUUID(),role:'admin'}).returning();
  const [outsider]=await db.insert(users).values({openId:randomUUID()}).returning();
  const {quoteId}=await createQuoteRequest({companyName:'Messages '+randomUUID(),contactName:'Contact',contactEmail:owner.email!,userId:owner.id});
  for(const content of ['  ','x'.repeat(10001)])await expect(createQuoteMessage({quoteId,content},owner.id)).rejects.toMatchObject({code:'BAD_REQUEST'});
  await expect(createQuoteMessage({quoteId,content:'Text',fromUserId:admin.id},owner.id)).rejects.toMatchObject({code:'BAD_REQUEST'});
  await expect(createQuoteMessage({quoteId,content:'Forbidden'},outsider.id)).rejects.toMatchObject({code:'FORBIDDEN'});
  await expect(getQuoteMessages(quoteId,outsider.id)).rejects.toMatchObject({code:'FORBIDDEN'});
  const own=await createQuoteMessage({quoteId,content:' Question '},owner.id);
  const reply=await createQuoteMessage({quoteId,content:'Reply'},admin.id);
  expect(own.message).toMatchObject({content:'Question',fromUserId:owner.id,quoteRequestId:quoteId});
  const thread=await getQuoteMessages(quoteId,owner.id);
  expect(thread.map(m=>m.id)).toEqual([own.message.id,reply.message.id]);
  expect(thread.map(m=>m.isRead)).toEqual([false,true]);
  expect(thread[1].fromRole).toBe('admin');
  expect((await db.select().from(messages).where(eq(messages.id,reply.message.id)))[0].isRead).toBe(true);
  await db.update(users).set({status:'suspended'}).where(eq(users.id,admin.id));
  await expect(createQuoteMessage({quoteId,content:'No longer allowed'},admin.id)).rejects.toMatchObject({code:'FORBIDDEN'});
  await expect(getQuoteMessages(quoteId,admin.id)).rejects.toMatchObject({code:'FORBIDDEN'});
  expect(await db.select().from(messages).where(eq(messages.quoteRequestId,quoteId))).toHaveLength(2);
 });
 it('uses current email/ownership, supports anonymous-request matching and does not mark a forbidden thread read',async()=>{
  const db=(await getDb())!;
  const email=randomUUID()+'@example.com';
  const [person]=await db.insert(users).values({openId:randomUUID(),email}).returning();
  const [admin]=await db.insert(users).values({openId:randomUUID(),role:'admin'}).returning();
  const {quoteId}=await createQuoteRequest({companyName:'Email '+randomUUID(),contactName:'Contact',contactEmail:email.toUpperCase()});
  await createQuoteMessage({quoteId,content:'Matched'},person.id);
  const reply=await createQuoteMessage({quoteId,content:'Unread'},admin.id);
  await db.update(users).set({email:randomUUID()+'@example.com'}).where(eq(users.id,person.id));
  await expect(getQuoteMessages(quoteId,person.id)).rejects.toMatchObject({code:'FORBIDDEN'});
  expect((await db.select().from(messages).where(eq(messages.id,reply.message.id)))[0].isRead).toBe(false);
  await expect(createQuoteMessage({quoteId,content:'Old email'},person.id)).rejects.toMatchObject({code:'FORBIDDEN'});
  await db.update(quoteRequests).set({userId:person.id}).where(eq(quoteRequests.id,quoteId));
  expect(await getQuoteMessages(quoteId,person.id)).toHaveLength(2);
  await expect(getQuoteMessages(-1,person.id)).rejects.toMatchObject({code:'BAD_REQUEST'});
 });
 it('recovers simultaneous identical sends once and still enforces current access on replay',async()=>{
  const db=(await getDb())!;
  const [owner]=await db.insert(users).values({openId:randomUUID()}).returning();
  const [admin]=await db.insert(users).values({openId:randomUUID(),role:'admin'}).returning();
  const make=()=>createQuoteRequest({companyName:'Replay '+randomUUID(),contactName:'Contact',contactEmail:'replay@example.com',userId:owner.id});
  const {quoteId}=await make();const {quoteId:other}=await make();
  const input={quoteId,content:' Original ',requestId:randomUUID()};
  const results=await Promise.all(Array.from({length:5},()=>createQuoteMessage(input,owner.id)));
  expect(results.filter(r=>!r.replayed)).toHaveLength(1);
  expect(new Set(results.map(r=>r.message.id)).size).toBe(1);
  const messageId=results[0].message.id;
  await getQuoteMessages(quoteId,admin.id);
  const replay=await createQuoteMessage({requestId:input.requestId.toUpperCase(),content:'Original',quoteId},owner.id);
  expect(replay).toMatchObject({replayed:true,message:{id:messageId,isRead:true}});
  await expect(createQuoteMessage({...input,content:'Changed'},owner.id)).rejects.toMatchObject({code:'CONFLICT'});
  await expect(createQuoteMessage({...input,quoteId:other},owner.id)).rejects.toMatchObject({code:'CONFLICT'});
  await expect(createQuoteMessage(input,admin.id)).rejects.toMatchObject({code:'CONFLICT'});
  await expect(createQuoteMessage({...input,requestId:'invalid'},owner.id)).rejects.toMatchObject({code:'BAD_REQUEST'});
  await db.update(users).set({status:'suspended'}).where(eq(users.id,owner.id));
  await expect(createQuoteMessage(input,owner.id)).rejects.toMatchObject({code:'FORBIDDEN'});
  await expect(db.update(quoteMessageRequests).set({fingerprint:'x'.repeat(64)}).where(eq(quoteMessageRequests.requestId,input.requestId))).rejects.toThrow();
  await expect(db.delete(quoteMessageRequests).where(eq(quoteMessageRequests.requestId,input.requestId))).rejects.toThrow();
  expect(await db.select().from(messages).where(eq(messages.quoteRequestId,quoteId))).toHaveLength(1);
 });

});
